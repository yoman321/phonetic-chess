def _old_user(case):
    listing = "\n".join(f"- {uci} ({san})" for uci, san in case["candidates"])
    last = case["last_move"]
    last_str = f"{last['uci']} ({last['san']})" if last else "(no moves yet)"
    return (
        f"Tone of the game so far: {case['prior_tone'] or '(none yet)'}\n"
        f"Last move played by the opponent: {last_str}\n"
        f"New player message: {case['message']}\n"
        f"Position FEN: {case['fen']}\n"
        f"Suggested moves (engine-recommended, uci (san)):\n{listing}\n"
        "Prefer one of the suggested moves — they are sound chess. Only pick "
        "a different legal UCI if no suggestion fits the tone at all. "
        "Always provide an updated tone_summary that reflects how the new "
        "message and the opponent's last move shift the game's mood."
    )


