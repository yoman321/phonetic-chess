def test_applying_each_last_move_to_its_previous_fen_gives_the_case_fen():
    for case in CASES:
        if case["last_move"] is None:
            continue
        board = chess.Board(case["prev_fen"])
        move = chess.Move.from_uci(case["last_move"]["uci"])
        assert move in board.legal_moves, case["id"]
        assert board.san(move) == case["last_move"]["san"], case["id"]
        board.push(move)
        assert board.fen() == case["fen"], case["id"]


def test_the_generator_calls_only_python_chess_and_rank_moves():
    """Invariant 7. No LLM, no provider, no network in the frozen-set tool."""
    source = (bench.BENCH_DIR / "generate_cases.py")
    if not source.exists():
        pytest.fail(
            "plans/machine-readable-move-prompt/generate_cases.py does not "
            "exist. It is built by Phase 2 — frozen-set tools."
        )
    text = source.read_text(encoding="utf-8")
    for banned in ("openai", "requests", "urllib", "httpx", "socket",
                   "pick_move_with_llm", "explain_move_with_llm"):
        assert banned not in text, f"generate_cases.py reaches {banned}"
    imported = set()
    for node in ast.walk(ast.parse(text)):
        if isinstance(node, ast.Import):
            imported.update(alias.name.split(".")[0] for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module:
            imported.add(node.module.split(".")[0])
    allowed = {
        "chess", "controller_operations", "json", "sys", "os", "pathlib",
        "argparse", "hashlib", "copy",
    }
    assert imported <= allowed, f"unexpected imports: {sorted(imported - allowed)}"


