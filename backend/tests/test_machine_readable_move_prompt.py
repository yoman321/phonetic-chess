"""Offline gates for plans/machine-readable-move-prompt.md.

Covers invariants 1-4 and 6-25. Nothing here calls a provider, a judge CLI, or
a database. Invariant 5 and the live halves of 10-24 are in
test_machine_readable_move_prompt_live.py.

These gates fix the contract the benchmark code must satisfy. The modules under
plans/machine-readable-move-prompt/ do not exist yet; `require_module` fails
naming the phase that builds each one.

Required benchmark surface
--------------------------
generate_cases.py   `python generate_cases.py --check` exits 0 only when the
                    regenerated bytes equal the committed fixture, and never
                    writes it.
judge.py            LABELS, JUDGE_PROMPT, make_items(records, seed),
                    build_request(items), parse_reply(text, expected_ids),
                    run_pass(records, call, seed),
                    run_two_passes(records, call, seeds), require_live()
metrics.py          stability, agreement, intensity_delta, off_list_rate,
                    validity, token_saving, verdict
run.py              plan_invocations(cases), render_messages(arm, case,
                    old_prompts), run_arm(...), build_report(payload),
                    require_live(), PACE_SECONDS

Fixture bytes
-------------
cases.json is json.dumps(payload, indent=2, ensure_ascii=False) + "\n" where
each case's derived fields are recomputed from its own seed fields:
  fen           = prev_fen with last_move.uci applied (when prev_fen is set)
  last_move.san = SAN of that uci in prev_fen
  candidates    = engine.rank_moves(chess.Board(fen))
Key order is id, phase, tone_tag, message, prior_tone, prev_fen, last_move,
fen, candidates.
"""
