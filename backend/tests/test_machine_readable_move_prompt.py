CASES = bench.cases()
CASE = CASES[0]


def _candidates(case):
    return [(uci, san) for uci, san in case["candidates"]]


def _last_move(case):
    if case["last_move"] is None:
        return None
    return (case["last_move"]["uci"], case["last_move"]["san"])


def _build(case):
    builder = bench.require_attr(llm, "build_move_prompt")
    return builder(
        case["message"], case["fen"], _candidates(case),
        case["prior_tone"], _last_move(case),
    )


@pytest.fixture
def provider(monkeypatch):
    fake = bench.FakeProvider(
        json.dumps({"uci": CASES[0]["candidates"][0][0], "tone_summary": "eager"})
    )
    monkeypatch.setattr(llm, "_client", fake)
    monkeypatch.setattr(llm, "LLM_BACKOFF_BASE", 0.0)
    return fake


def _pick(case, **kwargs):
    board = chess.Board(case["fen"])
    return llm.pick_move_with_llm(
        case["message"], case["fen"], _candidates(case),
        case["prior_tone"], _last_move(case),
        valid_ucis={m.uci() for m in board.legal_moves},
        **kwargs,
    )


